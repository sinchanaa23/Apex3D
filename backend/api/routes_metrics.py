"""
API Router for Offline Evaluation Metrics.
GET /api/metrics
"""

import json
import logging
from fastapi import APIRouter
from backend.config import METRICS_CANDIDATE_PATHS
from backend.models import MetricsResponse

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/api", tags=["Evaluation Metrics"])


@router.get(
    "/metrics",
    response_model=MetricsResponse,
    summary="Retrieve Offline Evaluation & Benchmark Metrics",
    description="Reads genuine evaluation metrics generated by offline notebooks. Returns 'not available' if training has not completed.",
)
async def get_evaluation_metrics():
    for candidate in METRICS_CANDIDATE_PATHS:
        if candidate.exists() and candidate.is_file():
            try:
                with open(candidate, "r", encoding="utf-8") as f:
                    metrics_data = json.load(f)
                return MetricsResponse(
                    status="available",
                    source_file=str(candidate.name),
                    metrics=metrics_data,
                    message="Official offline notebook evaluation metrics loaded.",
                )
            except Exception as e:
                logger.warning("Error reading metrics from %s: %s", candidate, e)

    return MetricsResponse(
        status="not available",
        message="Classifier training metrics have not been generated yet. Notebook 01 has not finished training.",
        metrics=None,
    )

